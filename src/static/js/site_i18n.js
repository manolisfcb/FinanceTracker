    var currentLang = null;

    function detectDefaultLang() {
        var saved = null;
        try {
            saved = window.localStorage.getItem(STORAGE_KEY);
        } catch (err) {
            saved = null;
        }
        if (saved && SUPPORTED.indexOf(saved) !== -1) return saved;

        var browserLang = (navigator.language || 'es').slice(0, 2).toLowerCase();
        if (browserLang === 'en') return 'en';
        if (browserLang === 'pt') return 'pt';
        return 'es';
    }

    function applyLangTo(root, lang) {
        var dict = translations[lang] || translations.es;

        root.querySelectorAll('[data-i18n]').forEach(function (el) {
            var value = dict[el.getAttribute('data-i18n')];
            if (value !== undefined) el.textContent = value;
        });

        ATTR_VARIANTS.forEach(function (attr) {
            root.querySelectorAll('[data-i18n-' + attr + ']').forEach(function (el) {
                var value = dict[el.getAttribute('data-i18n-' + attr)];
                if (value !== undefined) el.setAttribute(attr, value);
            });
        });
    }

    function setLangButtonsState(lang) {
        document.querySelectorAll('[data-lang-btn]').forEach(function (btn) {
            var isActive = btn.getAttribute('data-lang-btn') === lang;
            btn.classList.toggle('bg-ink', isActive);
            btn.classList.toggle('text-white', isActive);
            btn.classList.toggle('text-muted2', !isActive);
            btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
        });
    }

    function applyLang(lang) {
        currentLang = SUPPORTED.indexOf(lang) !== -1 ? lang : 'es';
        applyLangTo(document, currentLang);
        document.documentElement.setAttribute('lang', HTML_LANG[currentLang] || HTML_LANG.es);
        setLangButtonsState(currentLang);

        try {
            window.localStorage.setItem(STORAGE_KEY, currentLang);
        } catch (err) {
            // Private browsing or storage disabled — the switcher still
            // works for the current page, it just won't persist.
        }
    }

    // Event delegation so the switcher keeps working even if the buttons
    // (or the content around them) get replaced by an HTMX swap.
    document.addEventListener('click', function (event) {
        var btn = event.target.closest('[data-lang-btn]');
        if (btn) applyLang(btn.getAttribute('data-lang-btn'));
    });

    // Re-translate whatever HTMX just swapped in, so partial page updates
    // (pagination, feeds, inline edits) don't fall back to Spanish.
    document.body.addEventListener('htmx:afterSwap', function (event) {
        if (currentLang) applyLangTo(event.detail.target, currentLang);
    });

    applyLang(detectDefaultLang());
